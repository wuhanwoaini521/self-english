def _teach(
    *,
    ask: str = "怎么用",
    ask_en: str = "",
    ask_zh: str = "",
    replies: tuple[tuple[str, str], ...] = (),
    swaps: tuple[tuple[str, str], ...] = (),
    why_title: str = "",
    why_lines: tuple[str, ...] = (),
) -> dict:
    return {
        "ask": ask,
        "ask_en": ask_en,
        "ask_zh": ask_zh,
        "replies": [{"zh": zh, "en": en} for zh, en in replies],
        "swaps": [{"zh": zh, "en": en} for zh, en in swaps],
        "why_title": why_title,
        "why_lines": list(why_lines),
    }


def _note_from_teach(teach: dict) -> str:
    lines: list[str] = []
    if teach.get("ask"):
        lines.append(teach["ask"])
    for item in teach.get("replies") or []:
        lines.append(f"{item['zh']}　{item['en']}")
    swaps = teach.get("swaps") or []
    if swaps:
        lines.append(" ".join(f"{item['zh']} {item['en']}" for item in swaps))
    if teach.get("why_title"):
        lines.append(teach["why_title"])
    lines.extend(teach.get("why_lines") or [])
    return "\n".join(lines)


def _q(qid: str, prompt_en: str, prompt_zh: str, answer_id: str, options: list[tuple[str, str, str]]) -> dict:
    return {
        "id": qid,
        "prompt_en": prompt_en,
        "prompt_zh": prompt_zh,
        "options": [{"id": oid, "en": en, "zh": zh} for oid, en, zh in options],
        "answer_id": answer_id,
    }


def _gexpr(slug: str, english: str, chinese: str, *, phonetic: str, teach: dict, example_en: str, example_zh: str) -> dict:
    return _expr(
        slug, english, chinese, kind="grammar", phonetic=phonetic,
        note_zh=_note_from_teach(teach), example_en=example_en, example_zh=example_zh, mark="📘", teach=teach,
    )


def _vexpr(slug: str, english: str, chinese: str, *, phonetic: str, note_zh: str, example_en: str, example_zh: str) -> dict:
    return _expr(
        slug, english, chinese, kind="word", phonetic=phonetic,
        note_zh=note_zh, example_en=example_en, example_zh=example_zh, mark="📝",
    )


def _pexpr(slug: str, english: str, chinese: str, *, phonetic: str, note_zh: str, example_en: str, example_zh: str) -> dict:
    return _expr(
        slug, english, chinese, kind="phrase", phonetic=phonetic,
        note_zh=note_zh, example_en=example_en, example_zh=example_zh, mark="💬",
    )


