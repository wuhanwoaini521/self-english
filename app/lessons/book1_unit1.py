"""Original first-book unit: 12 lessons covering a beginner grammar sequence.

Texts, names and plots are original. The order follows a common first-stage
path (attention, be, jobs, greetings, whose, colour, there is, give me) so
the app can teach like a first book without copying New Concept English.
"""

from __future__ import annotations

